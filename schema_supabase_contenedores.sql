-- 7. VISTAS
CREATE OR REPLACE VIEW public.vista_seguimiento_salidas_activas AS
SELECT 
    s.id, s.code, s.tipo, s.medida, s.proveedor, s.cliente, s.destino,
    s.fecha_salida, s.hora_salida, s.retiro_estimado, s.traslado,
    s.traslado_monto, s.traslado_horas, s.remito_numero, s.usuario,
    c.estado AS estado_flota_actual, c.pago AS estado_pago
FROM public.seguimiento_contenedores s
LEFT JOIN public.contenedores c ON s.code = c.code
WHERE s.estado_movimiento = 'en_obra' OR s.fecha_entrada IS NULL;

CREATE OR REPLACE VIEW public.vista_resumen_proveedor_estado AS
SELECT 
    proveedor, estado, COUNT(*) AS cantidad,
    COUNT(*) FILTER (WHERE traslado = 'si') AS con_traslado
FROM public.contenedores
GROUP BY proveedor, estado;

